"""Reading a generated SBOL3 document.

Everything in `gcai.interop` needs the sbol extra. The imports are inside the
functions so that installing the client without it still works; the only cost
is an import on each call, which is negligible next to parsing a document.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from gcai.errors import GCAIError

if TYPE_CHECKING:  # pragma: no cover
    import sbol3

EXTRA_HINT = "this needs the SBOL libraries: pip install 'gc-ai-client[sbol]'"


def require_sbol3() -> Any:
    """The sbol3 module, or an error explaining how to get it."""
    try:
        import sbol3
    except ImportError as exc:  # pragma: no cover - depends on the installation
        raise GCAIError(EXTRA_HINT) from exc
    return sbol3


def load(document: bytes | str) -> "sbol3.Document":
    """Parse a generated document.

    It is read from memory rather than from a path on purpose: an empty
    `rdf:resource`, which a species with no URI produces, is otherwise resolved
    against wherever the file happens to sit.
    """
    sbol3 = require_sbol3()
    text = document.decode() if isinstance(document, bytes) else document
    doc = sbol3.Document()
    doc.read_string(text, sbol3.RDF_XML)
    return doc


def parent_component(doc: "sbol3.Document", name: str | None = None) -> "sbol3.Component":
    """The component holding the design's parts.

    This is the one with SubComponent features that is not the functional
    system the service builds alongside it.
    """
    sbol3 = require_sbol3()
    candidates = [
        obj
        for obj in doc.objects
        if isinstance(obj, sbol3.Component)
        and any(isinstance(feature, sbol3.SubComponent) for feature in obj.features)
        and sbol3.SBO_FUNCTIONAL_ENTITY not in list(obj.types)
    ]
    if name is not None:
        candidates = [obj for obj in candidates if obj.display_id == name]
    if not candidates:
        raise GCAIError(
            f"no parent component found{f' named {name!r}' if name else ''}; "
            "a document generated by GC-AI has one component holding SubComponent features"
        )
    if len(candidates) > 1:
        found = ", ".join(sorted(obj.display_id for obj in candidates))
        raise GCAIError(f"more than one parent component ({found}); name the one you mean")
    return candidates[0]


def term(uri: Any) -> str:
    """The trailing term of an ontology URI, such as SO:0000167."""
    return str(uri).rsplit("/", 1)[-1]
